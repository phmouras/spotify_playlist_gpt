@torch.inference_mode()
def generate_recommendations(model, prompt, num_recommendations, valid_track_tokens, temperature, top_k,):
    generated = prompt.clone()

    recommendations = [] # new recommendation tokens
    # block repeated songs: {songA, songB, ...} no recommended this songs anymore
    blocked_tokens = set(int(token) for token in prompt[0].tolist() if token in valid_track_tokens)

    for _ in range(num_recommendations):

        # if the sequence context is growing too long we must crop it at block_size
        idx_cond = generated[:, -model.config.block_size:] # [token[1], ..., token[block_size]]

        # forward the model to get the logits for the index in the sequence 
        with ctx:
            logits, _ = model(idx_cond) # tokens -> logits(scores)

        next_token_logits = logits[:, -1, :] / temperature # new token score after the last context token. [batch, position, tokens_vocab]

        # only tokens in the vocab
        allowed_mask = torch.zeros(model.config.vocab_size, dtype=torch.bool, device=device,) # (0,block_size)

        allowed_tokens = [token for token in valid_track_tokens
            if (token < model.config.vocab_size and token not in blocked_tokens)]

        if not allowed_tokens:
            break

        allowed_mask[allowed_tokens] = True

        next_token_logits[:,~allowed_mask] = float("-inf")

        effective_top_k = min(top_k, len(allowed_tokens))  # most top_k likely songs

        top_values, _ = torch.topk(next_token_logits, effective_top_k,) # if top_k > allowed tokens

        cutoff = top_values[:, [-1]] # minor value

        next_token_logits[next_token_logits < cutoff] = float("-inf") # all not permited tokens with -infty, with 0 when softmax

        probabilities = torch.softmax(next_token_logits, dim=-1,) # probalility distribution: sum(logits) =~ 1

        next_token = torch.multinomial(probabilities, num_samples=1,) # next song token. Multinomial: weighted random selection of songs

        token_value = int(next_token.item())

        recommendations.append(token_value)
        blocked_tokens.add(token_value) # dont recommend same songs

        generated = torch.cat((generated, next_token), dim=1,) # [songA, songB, songC(forecast)]

    return recommendations # (0, num_recommendations)

def get_track_descriptions(spotify_client, track_tokens, token_to_uri):

    track_descriptions = []

    for token in track_tokens:
        track_uri = token_to_uri.get(int(token))

        if not track_uri:
            continue

        try:
            track = spotify_client.track(track_uri)

        except spotipy.SpotifyException as error:
            print(f"Could not load track metadata for token {token}: {error}")
            continue

        if not track:
            continue

        track_name = track["name"]

        artist_names = [artist["name"] for artist in track["artists"]] # list
        album_name = track["album"]["name"] # dict

        artists = ", ".join(artist_names)

        track_descriptions.append(
            {
                "name": track_name,
                "artists": artists,
                "album":album_name
            }
        )

    return track_descriptions

