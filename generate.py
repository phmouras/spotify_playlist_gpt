def extract_playlist_id(playlist_reference): # for mode spotify
    """
    Extract a Spotify playlist ID from:
    - Spotify URL
    - Spotify URI
    - raw playlist ID
    """

    if not isinstance(playlist_reference, str):
        raise TypeError(
            "Playlist reference must be a string"
        )

    playlist_reference = playlist_reference.strip() # clean string

    if not playlist_reference:
        raise ValueError(
            "Playlist reference cannot be empty"
        )

    # Spotify URI:
    # spotify:playlist:37i9dQZF1DX...
    if playlist_reference.startswith("spotify:playlist:"):
        playlist_id = playlist_reference.split(":")[-1]

    # Spotify URL:
    # https://open.spotify.com/playlist/37i9dQZF1DX.....
    elif "open.spotify.com" in playlist_reference:
        parsed_url = urlparse(playlist_reference)

        path_parts = [part for part in parsed_url.path.split("/") if part]

        if (len(path_parts) < 2 or path_parts[0] != "playlist"):
            raise ValueError("Invalid Spotify playlist URL")

        playlist_id = path_parts[1] # /37i9dQZF1DX.....

    # Raw playlist ID
    else:
        playlist_id = playlist_reference

    if not playlist_id:
        raise ValueError("Could not extract the Spotify playlist ID")

    return playlist_id


