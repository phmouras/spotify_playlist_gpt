def create_spotify_client():
    """
    Authenticate the current user with Spotify OAuth
    and return an authenticated Spotify client
    """

    load_dotenv()

    client_id = os.getenv("SPOTIPY_CLIENT_ID")
    client_secret = os.getenv("SPOTIPY_CLIENT_SECRET")
    redirect_uri = os.getenv("SPOTIPY_REDIRECT_URI")

    missing_variables = [
        variable_name
        for variable_name, variable_value in {
            "SPOTIPY_CLIENT_ID": client_id,
            "SPOTIPY_CLIENT_SECRET": client_secret,
            "SPOTIPY_REDIRECT_URI": redirect_uri,
        }.items()
        if not variable_value
    ]

    if missing_variables:
        raise EnvironmentError(
            "Missing Spotify environment variables: "
            f"{', '.join(missing_variables)}"
        )

    auth_manager = SpotifyOAuth(  # Authenticator
        client_id=client_id,
        client_secret=client_secret,
        redirect_uri=redirect_uri,
        scope="playlist-read-private",
        cache_path=".cache-spotify",  # where track tokens will save
        open_browser=True,
    )

    return spotipy.Spotify(
        auth_manager=auth_manager,
        requests_timeout=20,
        retries=3,
    )

def load_playlist_track_uris(spotify_client, playlist_id):
    """
    Load all valid track URIs from a Spotify playlist.

    Handles pagination and ignores:
    - unavailable tracks
    - local files
    - podcast episodes
    - malformed items
    """

    track_uris = []
    # API: returns items from playlist: tracks
    response = spotify_client.playlist_items(   
        playlist_id,
        limit=50,   # pages limit
        offset=0,    # first item
        additional_types=("track",), # only type track
    )
    # process pages
    while response:  
        # print("Response keys:", response.keys())
        #print("First playlist item:", response["items"][0])
        for playlist_item in response["items"]:
            track = playlist_item.get("item")  # item = track{"name":..., "uri":..., "type":...}

            if not track:   # ignore items without track
                continue

            if track.get("type") != "track":  # only tracks
                continue

            if playlist_item.get("is_local"):  # ignore local files
                continue

            track_uri = track.get("uri")

            if track_uri:
                track_uris.append(track_uri)  # page items

        if response.get("next"):
            response = spotify_client.next(response) # advance other tracks

        else:
            break

    if not track_uris:
        raise ValueError(
            "No valid Spotify tracks in the playlist."
        )

    return track_uris

def convert_playlist_uris_to_tokens(playlist_track_uris, uri_to_token):
    """
    URIs not present in the vocabulary are ignored.
    """

    playlist_tokens = []
    unknown_uris = []

    for track_uri in playlist_track_uris:

        if track_uri in uri_to_token:
            track_token = uri_to_token[track_uri]
            playlist_tokens.append(track_token)
        else:
            unknown_uris.append(track_uri)

    if not playlist_tokens:
        raise ValueError(
            "None of the playlist tracks exist in the model vocabulary."
        )

    return playlist_tokens, unknown_uris

